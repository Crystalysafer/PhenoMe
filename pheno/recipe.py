"""Batch recipes: a step sequence as a file, so it can be reviewed and replayed.

Recording steps in the GUI already produces the in-memory form ``batchWork``
replays (``BATCH_PARAM["steps"]``). What was missing is the other direction: a
written recipe that can be loaded back, generated by something other than the
mouse, diffed, and attached to a paper.

That last point is the reason this module exists: a recipe is a file, the file
replays deterministically, and the numbers it produces can be defended -- anyone
holding it can reproduce the batch exactly.

Two kinds of step, and the difference matters:

* **portable** -- ``text``, ``color_correction``, ``ruler_detection``. These name
  something to look for or a reference to calibrate against, in terms that do not
  depend on where anything sits in the frame. A recipe built only from these
  replays on any batch.
* **positional** -- ``region``, ``click``. Pixel coordinates, tied to the frame
  they were recorded on. ``batch.py`` already refuses to replay these on images of
  another size, so a recipe carrying them declares the size it was made for.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

FORMAT = "phenome-batch-recipe"
VERSION = 1

PORTABLE_STEPS = ("text", "color_correction", "ruler_detection")
POSITIONAL_STEPS = ("region", "click")
STEP_TYPES = PORTABLE_STEPS + POSITIONAL_STEPS


class RecipeError(ValueError):
    """A recipe that cannot be used, with a message aimed at a person or a model."""


def _as_point(value, where: str) -> tuple[float, float]:
    if isinstance(value, dict):
        try:
            return float(value["x"]), float(value["y"])
        except (KeyError, TypeError, ValueError) as exc:
            raise RecipeError(f"{where} must be {{'x': number, 'y': number}}.") from exc
    if isinstance(value, (list, tuple)) and len(value) == 2:
        try:
            return float(value[0]), float(value[1])
        except (TypeError, ValueError) as exc:
            raise RecipeError(f"{where} must be two numbers.") from exc
    raise RecipeError(f"{where} must be {{'x': number, 'y': number}} or [x, y].")


def normalize_step(step) -> dict:
    """Check one step and return it in the stored shape.

    Raises :class:`RecipeError` with a message that says what is wrong and what the
    accepted step types are, because the caller is usually a model that can fix it.
    """
    if not isinstance(step, dict):
        raise RecipeError(f"Each step must be an object, got {type(step).__name__}.")

    kind = str(step.get("type") or "").strip().lower()
    if not kind:
        raise RecipeError(f"Every step needs a 'type', one of: {', '.join(STEP_TYPES)}.")
    if kind not in STEP_TYPES:
        raise RecipeError(f"Unknown step type {kind!r}; expected one of: {', '.join(STEP_TYPES)}.")

    if kind == "text":
        prompt = str(step.get("prompt") or "").strip()
        if not prompt:
            raise RecipeError("A text step needs a non-empty 'prompt', e.g. {'type': 'text', 'prompt': 'pod'}.")
        return {"type": "text", "prompt": prompt}

    if kind == "region":
        points = step.get("points")
        if points is None:
            # Legacy rectangle recipes: the two corners become a 4-vertex
            # polygon, so old recipe files keep replaying unchanged.
            start = _as_point(step.get("start_point"), "A region step needs 'points' or 'start_point'")
            end = _as_point(step.get("end_point"), "A legacy region step needs 'end_point'")
            points = [
                {"x": start[0], "y": start[1]},
                {"x": end[0], "y": start[1]},
                {"x": end[0], "y": end[1]},
                {"x": start[0], "y": end[1]},
            ]
        elif isinstance(points, list) and len(points) >= 3:
            points = [
                {"x": p[0], "y": p[1]}
                for p in (
                    _as_point(point, "region 'points' entries") for point in points
                )
            ]
        else:
            raise RecipeError(
                "A region step needs a 'points' list of at least 3 vertices "
                "(or legacy 'start_point'/'end_point').")
        count = step.get("fix_sample_count", "auto")
        if count in (None, "", "auto"):
            count = "auto"
        else:
            try:
                count = int(count)
            except (TypeError, ValueError) as exc:
                raise RecipeError("'fix_sample_count' must be an integer or 'auto'.") from exc
            if count < 1:
                raise RecipeError("'fix_sample_count' must be at least 1, or 'auto'.")
        return {
            "type": "region",
            "points": points,
            "fix_sample_count": count,
        }

    if kind == "click":
        points = step.get("points")
        if not isinstance(points, list) or not points:
            raise RecipeError("A click step needs a non-empty 'points' list.")
        cleaned = []
        for index, point in enumerate(points):
            if not isinstance(point, dict):
                raise RecipeError(f"points[{index}] must be an object.")
            try:
                cleaned.append(
                    {
                        "x": float(point["x"]),
                        "y": float(point["y"]),
                        "label": int(point.get("label", 1)),
                    }
                )
            except (KeyError, TypeError, ValueError) as exc:
                raise RecipeError(f"points[{index}] needs numeric 'x' and 'y'.") from exc
        return {"type": "click", "points": cleaned}

    # color_correction and ruler_detection carry no settings: they mean "do this".
    return {"type": kind}


def build_recipe(steps, *, image_size=None, note: str = "") -> dict:
    """Wrap steps into a recipe document.

    ``image_size`` is only meaningful for a recipe containing positional steps; it is
    recorded so the loader can refuse a batch it could not replay correctly rather
    than silently measuring the wrong pixels.
    """
    if not isinstance(steps, list) or not steps:
        raise RecipeError("A recipe needs at least one step.")

    normalized = [normalize_step(step) for step in steps]
    positional = any(step["type"] in POSITIONAL_STEPS for step in normalized)

    document = {
        "format": FORMAT,
        "version": VERSION,
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "steps": normalized,
        "portable": not positional,
    }
    if note:
        document["note"] = str(note)
    if positional:
        if not image_size or len(image_size) != 2:
            raise RecipeError(
                "This recipe contains region/click steps, which are pixel coordinates, so it needs "
                "'image_size': [width, height] of the frame they were recorded on."
            )
        document["image_size"] = [int(image_size[0]), int(image_size[1])]
    return document


def validate_recipe(document) -> list[str]:
    """Problems that would stop a recipe being replayed. Empty means usable."""
    if not isinstance(document, dict):
        return ["A recipe document must be a JSON object."]
    problems = []
    if document.get("format") != FORMAT:
        problems.append(f"format is {document.get('format')!r}, expected {FORMAT!r}.")
    if document.get("version") != VERSION:
        problems.append(f"version is {document.get('version')!r}, expected {VERSION}.")
    steps = document.get("steps")
    if not isinstance(steps, list) or not steps:
        problems.append("'steps' must be a non-empty list.")
        return problems
    for index, step in enumerate(steps):
        try:
            normalize_step(step)
        except RecipeError as exc:
            problems.append(f"steps[{index}]: {exc}")
    if any(isinstance(s, dict) and s.get("type") in POSITIONAL_STEPS for s in steps):
        size = document.get("image_size")
        if not isinstance(size, list) or len(size) != 2:
            problems.append(
                "region/click steps are pixel coordinates, so the recipe needs 'image_size': [w, h]."
            )
    return problems


def to_runtime_steps(document) -> list[dict]:
    """Recipe steps -> the in-memory form ``batchWork`` replays.

    Qt is imported here rather than at module scope: the recipe format itself is
    plain JSON and has to stay usable from the web service, which never constructs a
    QPoint.
    """
    problems = validate_recipe(document)
    if problems:
        raise RecipeError("; ".join(problems))

    from qtpy import QtCore

    runtime = []
    for step in document["steps"]:
        normalized = normalize_step(step)
        if normalized["type"] == "region":
            runtime.append(
                {
                    "type": "region",
                    "points": [
                        QtCore.QPoint(
                            int(round(point["x"])),
                            int(round(point["y"])),
                        )
                        for point in normalized["points"]
                    ],
                    "fix_sample_count": (
                        None if normalized["fix_sample_count"] == "auto" else normalized["fix_sample_count"]
                    ),
                }
            )
        elif normalized["type"] == "click":
            runtime.append({"type": "click", "points": list(normalized["points"])})
        else:
            runtime.append(dict(normalized))
    return runtime


def from_runtime_steps(steps, *, image_size=None, note: str = "") -> dict:
    """Build a recipe from live ``BATCH_PARAM`` steps (the recorder's direction)."""
    from pheno.batch import serialize_batch_step

    return build_recipe(
        [normalize_step(serialize_batch_step(step)) for step in steps],
        image_size=image_size,
        note=note,
    )


def describe(document) -> str:
    """A one-line-per-step summary, for a log, a dialog, or a model to read back."""
    lines = []
    for step in document.get("steps", []):
        kind = step.get("type")
        if kind == "text":
            lines.append(f"text: detect {step.get('prompt')!r}")
        elif kind == "region":
            count = step.get("fix_sample_count")
            vertices = step.get("points") or []
            xs = [p["x"] for p in vertices]
            ys = [p["y"] for p in vertices]
            extent = (
                f"({min(xs):.0f},{min(ys):.0f})-({max(xs):.0f},{max(ys):.0f})"
                if vertices else "?"
            )
            lines.append(
                f"region: {len(vertices)}-vertex polygon {extent}, "
                f"{'auto count' if count == 'auto' else str(count) + ' objects'}"
            )
        elif kind == "click":
            lines.append(f"click: {len(step.get('points', []))} point(s)")
        elif kind == "color_correction":
            lines.append("color correction")
        elif kind == "ruler_detection":
            lines.append("ruler detection")
    suffix = "" if document.get("portable", True) else f" (only on {document.get('image_size')})"
    return "\n".join(lines) + suffix


def write_recipe(document, path) -> Path:
    """Write a recipe, atomically, so a half-written file is never loaded."""
    problems = validate_recipe(document)
    if problems:
        raise RecipeError("; ".join(problems))
    target = Path(path).expanduser()
    if target.suffix.lower() != ".json":
        target = target.with_suffix(".phenoBatch.json")
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    temporary.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(target)
    return target


def read_recipe(path) -> dict:
    """Read and check a recipe file."""
    source = Path(path).expanduser()
    try:
        document = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RecipeError(f"{source} is not a readable recipe: {exc}") from exc
    problems = validate_recipe(document)
    if problems:
        raise RecipeError(f"{source} is not a usable recipe: " + "; ".join(problems))
    return document
